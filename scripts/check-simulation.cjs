const assert = require('node:assert/strict');
module.exports = async ({trader,client,base,userId,mongoose}) => {
  console.log('Checking provider prices and shared account trading...');
  await mongoose.connection.collection('users').updateOne({_id:new mongoose.Types.ObjectId(userId)},{$inc:{balance:10000}});
  const snapshot = async () => { const res=await trader.request.get(base+'/api/paper-trading');assert.equal(res.status(),200);return res.json(); };
  const metric = name => trader.locator('.sim-metrics article').filter({has:trader.locator('.sim-metric-label',{hasText:name})}).locator('strong');
  await trader.setViewportSize({width:1440,height:1000});
  await trader.goto(base+'/dashboard/trading');
  await trader.getByRole('heading',{name:'New position',exact:true}).waitFor();
  let before=await snapshot();
  assert.equal(before.history.length,0,'No invented sample trades imported');
  assert.equal(before.available,(await mongoose.connection.collection('users').findOne({_id:new mongoose.Types.ObjectId(userId)})).balance);
  assert.equal(before.equity,before.available);
  const feed=await (await trader.request.get(base+"/api/practice-market?once=1")).json();
  assert.equal(feed.quotes.BTC.reference,1000);assert.ok(feed.quotes.BTC.price>=960&&feed.quotes.BTC.price<=1040);
  await trader.getByRole('img',{name:'Trading price chart',exact:true}).waitFor();
  await trader.getByLabel('Lot size',{exact:true}).fill('0.001');
  await trader.getByLabel('Close after',{exact:true}).selectOption('15');
  await trader.getByRole('button',{name:'Open long position',exact:true}).click();
  await trader.getByRole('button',{name:'Close BTC / USD position',exact:true}).waitFor();
  const opened=await snapshot();assert.equal(opened.positions.length,1);assert.equal(opened.available,before.available-opened.margin);assert.equal(opened.equity,Math.round((opened.available+opened.margin+opened.unrealized)*100)/100);assert.ok(opened.margin>=720&&opened.margin<=780);
  await trader.goto(base+'/dashboard/wallet?view=withdraw');
  await trader.getByText(`Available: NGN ${opened.available.toLocaleString()}`,{exact:true}).waitFor();
  await trader.goto(base+'/dashboard');
  await trader.getByRole('heading',{name:'Overview',exact:true}).waitFor();
  await require('@playwright/test').expect(metric('Available balance')).toContainText(opened.available.toLocaleString('en-US',{minimumFractionDigits:2}));
  // Expire the fixture deadline instead of waiting on a wall-clock timer.
  await mongoose.connection.collection('paperpositions').updateOne({_id:new mongoose.Types.ObjectId(opened.positions[0].id)},{$set:{expiresAt:new Date(Date.now()-1000)}});
  let settled=await snapshot();assert.equal(settled.positions.length,0);assert.equal(Math.round(settled.available*100),Math.round((before.available+settled.realized)*100));assert.equal(settled.history[0].reason,'Timer completed');
  await trader.goto(base+'/dashboard/trading');
  await trader.getByRole('heading',{name:'New position',exact:true}).waitFor();
  await trader.getByLabel('Trading instrument',{exact:true}).selectOption('EUR');
  await trader.getByLabel('Lot size',{exact:true}).fill('0.001');
  await trader.getByRole('button',{name:'Sell / Short',exact:true}).click();
  await trader.getByRole('button',{name:'Open short position',exact:true}).click();
  await trader.getByRole('button',{name:'Close EUR / USD position',exact:true}).waitFor();
  const forex=await snapshot();assert.equal(forex.positions[0].units,100);assert.ok(forex.positions[0].margin>=7920&&forex.positions[0].margin<=8580);
  await trader.getByRole('button',{name:'Close EUR / USD position',exact:true}).click();
  await require('@playwright/test').expect(trader.getByRole('button',{name:'Close EUR / USD position',exact:true})).toHaveCount(0);
  await trader.reload();
  await trader.getByRole('button',{name:'Recent activity',exact:true}).click();
  await trader.locator('.sim-positions tbody tr').first().waitFor();
  assert.equal((await snapshot()).history.length,2);
  await trader.getByRole('button',{name:'How it works',exact:true}).click();
  await trader.getByRole('dialog').getByText(/No background execution worker/i).count();
  await trader.getByRole('button',{name:'Close simulation details',exact:true}).click();
  const download=trader.waitForEvent('download');await trader.getByRole('button',{name:'Export activity',exact:true}).click();await (await download).saveAs('test-results/account-trades.csv');
  await trader.screenshot({path:'test-results/market-trading-desktop.png',fullPage:true});
  await trader.getByRole('button',{name:'Switch to light theme',exact:true}).click();
  await trader.screenshot({path:'test-results/market-trading-light.png',fullPage:true});
  await trader.getByRole('button',{name:'Switch to dark theme',exact:true}).click();
  await trader.setViewportSize({width:390,height:844});
  await trader.screenshot({path:'test-results/market-trading-mobile.png',fullPage:true});
  const final=await snapshot();assert.equal(Math.round(final.available*100),Math.round((before.available+final.realized)*100));
  await trader.getByRole('button',{name:'Open positions',exact:false}).click();
  await trader.getByLabel('Trading instrument',{exact:true}).selectOption('SOL');
  const lotsInput=trader.getByLabel('Lot size',{exact:true});
  assert.equal(await lotsInput.getAttribute('max'),null);
  await lotsInput.fill('2');
  await trader.getByRole('button',{name:'Open long position',exact:true}).click();
  await trader.getByRole('button',{name:'Close SOL / USD position',exact:true}).waitFor();
  assert.equal((await snapshot()).positions[0].lots,2);
  await trader.getByRole('button',{name:'Close SOL / USD position',exact:true}).click();
  await require('@playwright/test').expect(trader.getByRole('button',{name:'Close SOL / USD position',exact:true})).toHaveCount(0);
  await trader.getByLabel('Size trade by',{exact:true}).selectOption('amount');
  await trader.getByLabel('Trade amount',{exact:true}).fill('123.45');
  const amountBefore=await snapshot();
  await trader.getByRole('button',{name:'Open long position',exact:true}).click();
  await trader.getByRole('button',{name:'Close SOL / USD position',exact:true}).waitFor();
  const amountPosition=await snapshot();
  assert.equal(amountPosition.positions[0].margin,123.45);
  assert.equal(Math.round((amountBefore.available-amountPosition.available)*100),12345);
  await trader.screenshot({path:'test-results/amount-sizing-mobile.png',fullPage:true});
  await trader.getByRole('button',{name:'Close SOL / USD position',exact:true}).click();
  await require('@playwright/test').expect(trader.getByRole('button',{name:'Close SOL / USD position',exact:true})).toHaveCount(0);
  console.log('Provider prices, shared wallet/overview balance, margin reservation, timed/manual closes, persistence, forex lots and exports passed.');
};
